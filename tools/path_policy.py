"""Workspace path validation shared by filesystem tools."""

from pathlib import Path


class WorkspacePathPolicy:
    """Resolve paths while preventing access outside a workspace root."""

    def __init__(self, root):
        self.root = Path(root).resolve()

    def path_is_within_root(self, resolved):
        probe = resolved
        while not probe.exists() and probe.parent != probe:
            probe = probe.parent
        for candidate in (probe, *probe.parents):
            try:
                if candidate.samefile(self.root):
                    return True
            except OSError:
                continue
        return False

    def resolve(self, raw_path):
        path = Path(raw_path)
        path = path if path.is_absolute() else self.root / path
        resolved = path.resolve()
        if not self.path_is_within_root(resolved):
            raise ValueError(f"path escapes workspace: {raw_path}")
        return resolved
